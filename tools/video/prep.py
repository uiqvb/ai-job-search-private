"""Phase 1, step 1: transcribe every raw take and find every attempt of every script line.

    python tools/video/prep.py documents/video/<company>

Works for one long take, one file per line, or a mix. Writes:
  pipeline/transcripts/<file>.json   word timings (cached)
  pipeline/takes.json                candidate attempts per line, with quality numbers
  pipeline/takes.md                  the same for the cutter agent, plus the full timestamped transcript
"""

import sys
from difflib import SequenceMatcher

import numpy as np

import vlib

PAUSE = 0.5          # a gap this long splits the transcript into phrases
MIN_SCORE = 0.45     # weakest fuzzy match still listed as an attempt
MAX_GAP = 2.5        # an attempt never spans a silence longer than this
BETTER = 0.12        # drop a window that another line matches this much better


def phrases(words):
    out, cur = [], []
    for w in words:
        if cur and w["s"] - cur[-1]["e"] > PAUSE:
            out.append(cur)
            cur = []
        cur.append(w)
    if cur:
        out.append(cur)
    return out


def find_attempts(line_toks, words):
    """Non-overlapping windows of the transcript that best match a script line."""
    toks = [vlib.norm(w["w"]) for w in words]
    m = len(line_toks)
    if not m:
        return []
    lo, hi = max(2, int(m * 0.5)), int(m * 2.0) + 3
    best = []
    # index of the first word after each long silence, so no window spans one
    breaks = [k for k in range(1, len(words)) if words[k]["s"] - words[k - 1]["e"] > MAX_GAP] + [len(words)]
    for i in range(len(toks)):
        top = (0, 0)
        limit = next(b for b in breaks if b > i) - i      # words available before the next long silence
        for n in range(lo, min(hi, limit) + 1):
            r = SequenceMatcher(None, line_toks, toks[i:i + n], autojunk=False).ratio()
            if r > top[0]:
                top = (r, n)
        if top[0] >= MIN_SCORE:
            best.append((top[0], i, top[1]))
    best.sort(reverse=True)
    taken, out = [], []
    for r, i, n in best:
        if any(i < b and a < i + n for a, b in taken):
            continue
        taken.append((i, i + n))
        out.append((r, i, n))
    return sorted(out, key=lambda x: x[1])


def quality(win, env, t0):
    """Numbers the cutter uses to judge an attempt."""
    toks = [vlib.norm(w["w"]) for w in win]
    gaps = [b["s"] - a["e"] for a, b in zip(win, win[1:])]
    repeats = sum(1 for a, b in zip(toks, toks[1:]) if a == b and a not in ("that", "had"))
    stumble = any(w["w"].endswith("-") for w in win) or repeats > 0
    lowconf = [w["w"] for w in win if w.get("p", 1) < 0.45]
    s, e = win[0]["s"], win[-1]["e"]
    seg = env[int((s - t0) / vlib.HOP): int((e - t0) / vlib.HOP) + 1]
    return {
        "longest_pause": round(max(gaps), 2) if gaps else 0,
        "fillers": [w for w in toks if w in vlib.FILLERS and w != "like"],
        "repeats": repeats, "stumble": stumble, "unclear_words": lowconf,
        "level_db": round(float(np.percentile(seg, 80)), 1) if len(seg) else None,
    }


def main(folder):
    pj = vlib.Project(folder)
    prompt = pj.cfg.get("transcribe_prompt", "")
    files = pj.raw_files()
    takes = {"files": [], "lines": []}
    md = [f"# Takes for {pj.name}", "",
          "Generated by tools/video/prep.py. Times are seconds in each raw file.", ""]
    all_words = {}
    for f in files:
        print(f"transcribing {f.name} ...", flush=True)
        words = vlib.transcribe(f, pj.path("transcripts", f.stem + ".json"), prompt)
        info = vlib.probe(f)
        all_words[f.name] = words
        takes["files"].append({"file": f.name, "duration": round(info["duration"], 2),
                               "size": [info["width"], info["height"]], "words": len(words)})
    envs = {name: vlib.rms_db(vlib.audio(pj.raw(name))) for name in all_words}

    md += ["## Candidate attempts per line", "",
           "Score = how closely the words match the script line (1.0 = exact). "
           "'last' = the latest attempt in time. Lines are pointers; Manit says them his own way, so a lower score can still be a good take.", ""]
    order = {f.name: k for k, f in enumerate(files)}
    raw = {}
    for line in pj.lines:
        lt = vlib.tokens(line["text"])
        raw[line["id"]] = [(name, r, i, n) for name, words in all_words.items() for r, i, n in find_attempts(lt, words)]

    def beaten(lid, name, r, i, n):
        """True when the same stretch of speech matches another line clearly better."""
        return any(o != lid and nm == name and r2 > r + BETTER and i < i2 + n2 and i2 < i + n
                   for o, lst in raw.items() for nm, r2, i2, n2 in lst)

    for line in pj.lines:
        cands = []
        for name, r, i, n in raw[line["id"]]:
            if beaten(line["id"], name, r, i, n):
                continue
            words = all_words[name]
            win = words[i:i + n]
            cands.append({"file": name, "start": win[0]["s"], "end": win[-1]["e"], "score": round(r, 2),
                          "said": " ".join(w["w"] for w in win), **quality(win, envs[name], 0.0)})
        cands.sort(key=lambda c: (order[c["file"]], c["start"]))
        if cands:
            cands[-1]["last"] = True
        takes["lines"].append({"id": line["id"], "text": line["text"], "attempts": cands})
        md += [f"### {line['id']}", f"Script: {line['text']}", ""]
        if not cands:
            md += ["*No attempt found by matching. Search the transcript below by hand.*", ""]
            continue
        md += ["| # | file | start-end | score | said | pause | stumble | unclear |",
               "|---|---|---|---|---|---|---|---|"]
        for k, c in enumerate(cands, 1):
            md.append(f"| {k}{' last' if c.get('last') else ''} | {c['file']} | {c['start']:.2f}-{c['end']:.2f} | {c['score']} | "
                      f"{c['said'][:110]} | {c['longest_pause']} | {'yes' if c['stumble'] else ''} | {' '.join(c['unclear_words'])} |")
        md.append("")

    md += ["## Full transcript (phrases split at pauses over 0.5 s)", ""]
    for name, words in all_words.items():
        md += [f"### {name}", "", "```"]
        for p in phrases(words):
            md.append(f"[{p[0]['s']:7.2f}-{p[-1]['e']:7.2f}] " + " ".join(f"{w['w']}" for w in p))
        md += ["```", ""]
        md += ["Word timings: pipeline/transcripts/" + name.rsplit(".", 1)[0] + ".json", ""]
    pj.write_json(takes, "takes.json")
    pj.path("takes.md").write_text("\n".join(md), encoding="utf-8")
    found = sum(1 for L in takes["lines"] if L["attempts"])
    print(f"ok: {len(files)} file(s), {found}/{len(pj.lines)} lines matched -> {pj.path('takes.md')}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
